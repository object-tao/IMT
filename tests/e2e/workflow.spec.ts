import { test, expect } from '@playwright/test';
test('从资源体验到生成、调整、保存、客户文档及档案', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'每一程，都有更好的连接。'})).toBeVisible();
  await page.getByRole('button',{name:'载入示例数据',exact:true}).click();
  await page.getByRole('button',{name:'确认载入示例'}).click();
  await expect(page.getByLabel('起运城市',{exact:true})).toHaveValue('上海');
  await page.getByRole('button',{name:'生成运输方案'}).click();
  await expect(page.locator('.candidate-card').first()).toBeVisible();
  await page.getByRole('button',{name:'查看与调整'}).first().click();
  await page.getByRole('button',{name:'保存方案',exact:true}).click();
  await expect(page.getByText(/已保存版本 V1/)).toBeVisible();
  const [download] = await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Word',exact:true}).click()]);
  expect(download.suggestedFilename()).toContain('.docx');
  const [printPage] = await Promise.all([page.waitForEvent('popup'),page.getByRole('link',{name:'打印 / PDF'}).click()]);
  await expect(printPage.locator('body')).not.toContainText('示例 ·');
  await printPage.pdf({path:'test-results/customer-plan.pdf',format:'A4',landscape:true,printBackground:true});
  await printPage.close();
  await page.getByRole('button',{name:'重新校验'}).click();
  await page.getByRole('button',{name:'保存新版本'}).click();
  await expect(page.getByText(/已保存版本 V2/)).toBeVisible();
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:/方案档案/}).click();
  await expect(page.getByText('V2',{exact:true})).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:/方案档案/}).click();
  await expect(page.getByText('V1',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
test('资源编辑和移动端布局', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button',{name:/资源网络/}).click();
  await page.getByRole('button',{name:'新增供应商'}).click();
  await page.getByRole('textbox',{name:'名称',exact:true}).fill('验收测试供应商');
  await page.getByRole('button',{name:'保存供应商'}).click();
  await expect(page.locator('.resource-table')).toContainText('验收测试供应商');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'方案工作台'}).click();
  await expect(page.getByRole('heading',{name:'运输需求',exact:true})).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
